#!/usr/bin/env node
// Render a scoped diagram and open dependencies from the checked atlas record.
import {readFileSync, writeFileSync} from 'node:fs';

const map = JSON.parse(readFileSync(new URL('../evidence/code-atlas/action33-frontier.json', import.meta.url), 'utf8'));
const observed = new Set(map.edge_observation.original_instruction_synthetic_sites);
const direct = map.ordered_constraints.filter(row => row.target);
const used = new Set(direct.flatMap(row => [row.owner, row.target]));
const safe = value => value.replace(/[|<>"\r\n]/g, ' ');
const role = new Map(map.functions.map(row => [row.address, row.role]));
const lines = [
  '# Action 0x33 connected dependency frontier',
  '',
  'Generated by `node scripts/render-action33-frontier.mjs --write` from `evidence/code-atlas/action33-frontier.json`.',
  'Arrows marked “observed synthetic” were reached by original instructions on labelled synthetic state. “Static/unreached” arrows are assembly-mapped constraints or a stop-before boundary. This diagram does not establish a live match or a completed penalty attempt.',
  '',
  '```mermaid',
  'flowchart LR',
  ...[...used].sort().map(address => `  f_${address}["${address} ${safe(role.get(address))}"]`),
  ...direct.map(row => `  f_${row.owner} -->|${row.site} ${observed.has(row.site) ? 'observed synthetic' : 'static/unreached'}| f_${row.target}`),
  '```',
  '',
  `Original resolver prefix: ${map.completed_prefix.cases} cases and ${map.completed_prefix.original_instruction_steps} original steps, ending before ${map.completed_prefix.stop_before}.`,
  `Original effect continuation: ${map.continued_effect.cases} cases and ${map.continued_effect.additional_original_instruction_steps} additional steps, ending before ${map.continued_effect.stop_before}.`,
  `TypeScript entry prefix: ${map.typescript_entry_prefix.cases} original-entry cases from ${map.typescript_entry_prefix.entry} to before ${map.typescript_entry_prefix.stop_before}, plus ${map.typescript_entry_prefix.helper_cases} standalone grid-helper cases.`,
  `Separate TypeScript interior segment: ${map.typescript_composition.cases} original-produced checkpoints from ${map.typescript_composition.start} to before ${map.typescript_composition.stop_before}; first full-entry TypeScript gap ${map.typescript_composition.first_full_entry_gap}. These TypeScript paths are not joined.`,
  `Separate original lifecycle fixtures: ${map.lifecycle_fixture.lookup_returns} lookup returns, ${map.lifecycle_fixture.placement_frontiers} placement frontiers, ${map.lifecycle_fixture.nonnull_status_frontiers} nonnull status frontiers, ${map.lifecycle_fixture.null_diagnostic_frontiers} null diagnostics and ${map.lifecycle_fixture.constructor_os_frontiers} constructor OS frontiers; no enclosing live game caller.`,
  '',
  '## Evidence state',
  '',
  ...Object.entries(map.milestone_status).map(([key, value]) => `- ${key.replaceAll('_', ' ')}: ${safe(value)}.`),
  '',
  '## Open dependencies',
  '',
  '| Dependency | First site | Required evidence | Assignment |',
  '| --- | --- | --- | --- |',
  ...map.frontier.map(row => `| ${safe(row.id)} | ${row.first_site} | ${safe(row.requirement)} | ${safe(row.next_assignment)} |`),
  '',
];
const result = lines.join('\n');
if (process.argv.includes('--write')) writeFileSync(new URL('../reports/action33-frontier-30.md', import.meta.url), result, 'utf8');
else process.stdout.write(result);
